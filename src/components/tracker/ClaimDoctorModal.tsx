import React, { useState } from 'react';
import * as Dialog from '@radix-ui/react-dialog';
import { useNavigate } from 'react-router-dom';
import { useLanguage } from '@/store/useLanguageStore';
import { AP_REJECTION_DIAGNOSTICS } from '@/config/rejectionDiagnostics';
import { TrackedApplication } from '@/types/tracker';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { ROUTES } from '@/config/routes';
import {
  Stethoscope,
  X,
  Printer,
  Copy,
  Check,
  MapPin,
  PhoneCall,
  CheckCircle2,
} from 'lucide-react';

interface ClaimDoctorModalProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  application: TrackedApplication;
  district?: string;
  onSelectReason: (reasonCode: string) => void;
}

export const ClaimDoctorModal: React.FC<ClaimDoctorModalProps> = ({
  open,
  onOpenChange,
  application,
  district,
  onSelectReason,
}) => {
  const { pick, getFontClass } = useLanguage();
  const navigate = useNavigate();

  const [selectedCode, setSelectedCode] = useState<string>(
    application.rejection_reason_code || AP_REJECTION_DIAGNOSTICS[0].code
  );
  const [copiedSlip, setCopiedSlip] = useState(false);

  const activeDiag =
    AP_REJECTION_DIAGNOSTICS.find((d) => d.code === selectedCode) ||
    AP_REJECTION_DIAGNOSTICS[0];

  const handleSaveDiagnosis = (code: string) => {
    setSelectedCode(code);
    onSelectReason(code);
  };

  const buildGrievanceSlipText = (): string => {
    return [
      '=== AP GRAMA/WARD SACHIVALAYAM & 1902 PGRS RE-VERIFICATION SLIP ===',
      '(Generated by ClaimSaathi • Zero Personal IDs Stored Digitally)',
      `Date: ${new Date().toISOString().slice(0, 10)}`,
      `Scheme: ${application.name_en} (${application.scheme_code})`,
      `Grievance Category: ${activeDiag.grievanceCategoryCode}`,
      `Issue Reported: ${activeDiag.title_en} / ${activeDiag.title_te}`,
      `District: ${district && district !== 'unknown' ? district : '____________________'}`,
      'Applicant Name (Write by hand at counter): ____________________________',
      'Acknowledgement / Petition Ref No (Write by hand): ____________________',
      '',
      'Requested Officer Action:',
      ...activeDiag.fixSteps_en.map((s, idx) => `${idx + 1}. ${s}`),
      '',
      'Official Toll-Free Escalation: 1902 | Portal: https://pgrs.ap.gov.in/',
    ].join('\n');
  };

  const handleCopySlip = async () => {
    try {
      await navigator.clipboard.writeText(buildGrievanceSlipText());
      setCopiedSlip(true);
      setTimeout(() => setCopiedSlip(false), 2200);
    } catch {
      setCopiedSlip(false);
    }
  };

  return (
    <Dialog.Root open={open} onOpenChange={onOpenChange}>
      <Dialog.Portal>
        <Dialog.Overlay className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs" />
        <Dialog.Content
          className="fixed left-1/2 top-1/2 z-50 w-[95vw] max-w-2xl max-h-[90vh] -translate-x-1/2 -translate-y-1/2 overflow-y-auto rounded-2xl bg-white p-5 sm:p-6 shadow-2xl border border-border focus:outline-none"
        >
          <div className="flex items-start justify-between gap-3 border-b border-border pb-4">
            <div className="space-y-1">
              <Badge className="bg-rose-100 text-rose-900 border border-rose-300 font-bold">
                <Stethoscope className="h-3.5 w-3.5 mr-1" aria-hidden="true" />
                {pick(
                  'Claim Doctor • Rejection & DBT Troubleshooter',
                  'క్లెయిమ్ డాక్టర్ • తిరస్కరణ & DBT పరిష్కార సహాయకుడు',
                  'क्लेम डॉक्टर • अस्वीकृति एवं DBT समस्या निवारक'
                )}
              </Badge>
              <Dialog.Title className={`text-lg sm:text-xl font-extrabold text-primary ${getFontClass()}`}>
                {pick(application.name_en, application.name_te, application.name_hi)}
              </Dialog.Title>
              <Dialog.Description className={`text-xs sm:text-sm text-muted ${getFontClass()}`}>
                {pick(
                  'Select why your application was rejected or held to get exact remediation steps and a printable 1902 / Sachivalayam re-verification slip.',
                  'మీ దరఖాస్తు ఎందుకు తిరస్కరించబడిందో లేదా ఆగిపోయిందో ఎంచుకుని, పరిష్కార మార్గాలు & 1902 పునఃపరిశీలన స్లిప్ పొందండి.',
                  'चयन करें कि आपका आवेदन क्यों रुका या अस्वीकृत हुआ, और सटीक समाधान व 1902 पुनर्सत्यापन पर्ची प्राप्त करें।'
                )}
              </Dialog.Description>
            </div>

            <Dialog.Close asChild>
              <button
                type="button"
                className="rounded-full p-2 text-muted hover:bg-slate-100 hover:text-body min-h-[40px] min-w-[40px] flex items-center justify-center"
                aria-label="Close"
              >
                <X className="h-5 w-5" aria-hidden="true" />
              </button>
            </Dialog.Close>
          </div>

          <div className="py-4 space-y-5">
            {/* Step 1: Pick Rejection Cause */}
            <div className="space-y-2">
              <p className={`text-xs font-bold uppercase tracking-wider text-muted ${getFontClass()}`}>
                {pick(
                  '1. Select Rejection / Hold Reason:',
                  '1. తిరస్కరణ / పెండింగ్ కారణాన్ని ఎంచుకోండి:',
                  '1. अस्वीकृति का कारण चुनें:'
                )}
              </p>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                {AP_REJECTION_DIAGNOSTICS.map((diag) => {
                  const isSelected = diag.code === selectedCode;
                  return (
                    <button
                      key={diag.code}
                      type="button"
                      onClick={() => handleSaveDiagnosis(diag.code)}
                      className={`text-left p-3 rounded-xl border text-xs sm:text-sm transition-all ${getFontClass()} ${
                        isSelected
                          ? 'border-rose-600 bg-rose-50/70 text-rose-950 font-bold shadow-xs'
                          : 'border-border bg-white hover:bg-slate-50 text-body font-medium'
                      }`}
                    >
                      {pick(diag.title_en, diag.title_te, diag.title_hi)}
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Step 2: Actionable Fix Steps */}
            <div className="rounded-xl border border-emerald-300 bg-emerald-50/50 p-4 space-y-3">
              <div className="flex flex-wrap items-center justify-between gap-2">
                <h4 className={`text-sm font-extrabold text-emerald-950 flex items-center gap-1.5 ${getFontClass()}`}>
                  <CheckCircle2 className="h-4 w-4 text-emerald-700 shrink-0" aria-hidden="true" />
                  <span>
                    {pick(
                      '2. Exact Steps to Fix & Re-Apply:',
                      '2. పరిష్కరించడానికి చేయవలసిన పనులు:',
                      '2. सुधार एवं पुनर्सत्यापन के चरण:'
                    )}
                  </span>
                </h4>
                <span className="text-[11px] font-mono text-emerald-900 bg-white px-2 py-0.5 rounded border border-emerald-200">
                  {activeDiag.grievanceCategoryCode}
                </span>
              </div>

              <ol className={`list-decimal pl-5 space-y-1.5 text-xs sm:text-sm text-slate-800 ${getFontClass()}`}>
                {(pick(
                  activeDiag.fixSteps_en.join('||'),
                  activeDiag.fixSteps_te.join('||'),
                  activeDiag.fixSteps_hi.join('||')
                ) || '')
                  .split('||')
                  .map((step, idx) => (
                    <li key={idx} className="leading-relaxed">
                      {step}
                    </li>
                  ))}
              </ol>

              <p className={`text-xs font-semibold text-emerald-900 pt-1 ${getFontClass()}`}>
                <strong>{pick('Where to visit:', 'ఎక్కడికి వెళ్ళాలి:', 'कहाँ जाएं:')}</strong>{' '}
                {pick(activeDiag.whereToGo_en, activeDiag.whereToGo_te, activeDiag.whereToGo_hi)}
              </p>
            </div>

            {/* Step 3: Bilingual Printable 1902 Grievance Re-Verification Slip */}
            <div className="rounded-xl border border-slate-300 bg-slate-50 p-4 space-y-2">
              <p className="text-xs font-bold text-primary">
                {pick(
                  '3. Bilingual 1902 / Sachivalayam Grievance Slip (Zero Digital PII):',
                  '3. 1902 / సచివాలయ పునఃపరిశీలన వినతి పత్రం (డిజిటల్ PII లేకుండా):',
                  '3. 1902 / सचिवालय पुनर्सत्यापन पर्ची (बिना डिजिटल PII):'
                )}
              </p>
              <pre className="whitespace-pre-wrap text-[11px] font-mono bg-white border border-slate-200 rounded-lg p-3 text-slate-800 max-h-[150px] overflow-y-auto">
                {buildGrievanceSlipText()}
              </pre>
            </div>

            {/* Actions */}
            <div className="flex flex-wrap items-center justify-between gap-2 pt-1">
              <div className="flex flex-wrap gap-2">
                <Button
                  type="button"
                  onClick={() => window.print()}
                  className={`min-h-[42px] text-xs sm:text-sm font-bold ${getFontClass()}`}
                >
                  <Printer className="h-4 w-4 mr-1.5" aria-hidden="true" />
                  {pick('Print Grievance Slip', 'స్లిప్ ప్రింట్ చేయండి', 'पर्ची प्रिंट करें')}
                </Button>

                <Button
                  type="button"
                  variant="outline"
                  onClick={handleCopySlip}
                  className={`min-h-[42px] text-xs sm:text-sm ${getFontClass()}`}
                >
                  {copiedSlip ? (
                    <Check className="h-4 w-4 mr-1.5 text-emerald-700" aria-hidden="true" />
                  ) : (
                    <Copy className="h-4 w-4 mr-1.5" aria-hidden="true" />
                  )}
                  {copiedSlip
                    ? pick('Copied!', 'కాపీ అయింది!', 'कॉपी हो गया!')
                    : pick('Copy Slip Text', 'టెక్స్ట్ కాపీ చేయండి', 'टेक्स्ट कॉपी करें')}
                </Button>
              </div>

              <div className="flex flex-wrap gap-2">
                <a
                  href="tel:1902"
                  className="inline-flex items-center justify-center rounded-md px-3 min-h-[42px] text-xs font-bold bg-emerald-700 hover:bg-emerald-800 text-white"
                >
                  <PhoneCall className="h-3.5 w-3.5 mr-1.5" aria-hidden="true" />
                  Call 1902
                </a>

                <Button
                  type="button"
                  variant="outline"
                  onClick={() => {
                    onOpenChange(false);
                    const q =
                      district && district !== 'unknown'
                        ? `?district=${encodeURIComponent(district)}`
                        : '';
                    navigate(`${ROUTES.SERVICE_CENTRES}${q}`);
                  }}
                  className={`min-h-[42px] text-xs ${getFontClass()}`}
                >
                  <MapPin className="h-3.5 w-3.5 mr-1.5 text-emerald-700" aria-hidden="true" />
                  {pick('Nearest Sachivalayam', 'సమీప సచివాలయం', 'नजदीकी सचिवालय')}
                </Button>
              </div>
            </div>
          </div>
        </Dialog.Content>
      </Dialog.Portal>
    </Dialog.Root>
  );
};
